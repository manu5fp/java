/**
 * Ejemplo 3: Condicionales
 * Repasa:
 * - Uso de if-else
 * - Operadores de comparación
 */
public class Ejemplo03_Condicionales {
    public static void main(String[] args) {
        int edad = 20;

        if (edad >= 18) {
            System.out.println("Eres mayor de edad");
        } else {
            System.out.println("Eres menor de edad");
        }
    }
}
